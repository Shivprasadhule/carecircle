"""SQLite persistence for CareCircle (multi-family).

Hierarchy: family -> {patients, members (users), facilities}. Clinicians are assigned to patients across families.
All data is synthetic. Every care table is keyed by patient_id so queries can be scoped to what an account may see.
"""
from __future__ import annotations

import os
import sqlite3
from contextlib import contextmanager
from datetime import datetime
from pathlib import Path

DB_PATH = Path(os.environ.get("CARECIRCLE_DB", Path(__file__).resolve().parents[2] / "data" / "carecircle.db"))
SCHEMA_VERSION = 2

SCHEMA = """
CREATE TABLE IF NOT EXISTS families (id TEXT PRIMARY KEY, name TEXT, city TEXT, notes TEXT);
CREATE TABLE IF NOT EXISTS facilities (
  id INTEGER PRIMARY KEY, family_id TEXT, name TEXT, kind TEXT, address TEXT, phone TEXT, active INTEGER DEFAULT 1);
CREATE TABLE IF NOT EXISTS patients (
  id TEXT PRIMARY KEY, family_id TEXT, name TEXT, age INTEGER, sex TEXT, conditions TEXT, allergies TEXT, language TEXT,
  facility_id INTEGER, instructions TEXT DEFAULT '', active INTEGER DEFAULT 1);
CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY, name TEXT, role TEXT, family_id TEXT, patient_id TEXT, password_hash TEXT,
  phone TEXT, notify_level TEXT DEFAULT 'urgent', blurb TEXT, active INTEGER DEFAULT 1, created_at TEXT, pw_changed INTEGER DEFAULT 0);
CREATE TABLE IF NOT EXISTS clinician_patients (user_id TEXT, patient_id TEXT, PRIMARY KEY (user_id, patient_id));
CREATE TABLE IF NOT EXISTS medications (
  id INTEGER PRIMARY KEY, patient_id TEXT, name TEXT, dose TEXT, purpose TEXT, times TEXT, with_food INTEGER DEFAULT 0,
  notes TEXT, prescriber TEXT, active INTEGER DEFAULT 1, started_at TEXT, stopped_at TEXT);
CREATE TABLE IF NOT EXISTS dose_log (
  id INTEGER PRIMARY KEY, med_id INTEGER, day TEXT, slot TEXT, status TEXT, logged_at TEXT, UNIQUE(med_id, day, slot));
CREATE TABLE IF NOT EXISTS checkins (id INTEGER PRIMARY KEY, patient_id TEXT, ts TEXT, mood INTEGER, pain INTEGER, sleep_hours REAL, note TEXT);
CREATE TABLE IF NOT EXISTS vitals (id INTEGER PRIMARY KEY, patient_id TEXT, ts TEXT, kind TEXT, value REAL, value2 REAL, unit TEXT);
CREATE TABLE IF NOT EXISTS appointments (
  id INTEGER PRIMARY KEY, patient_id TEXT, title TEXT, doctor TEXT, starts_at TEXT, facility_id INTEGER, location TEXT,
  needs_ride INTEGER DEFAULT 0, notes TEXT, status TEXT DEFAULT 'scheduled');
CREATE TABLE IF NOT EXISTS alerts (
  id INTEGER PRIMARY KEY, patient_id TEXT, ts TEXT, severity TEXT, title TEXT, detail TEXT, status TEXT DEFAULT 'open', notified TEXT);
CREATE TABLE IF NOT EXISTS memories (id INTEGER PRIMARY KEY, patient_id TEXT, ts TEXT, kind TEXT, content TEXT);
-- Append-only: rows are only ever inserted (see audit.py). Chat content is NOT copied here, only who did what.
CREATE TABLE IF NOT EXISTS audit (
  id INTEGER PRIMARY KEY, ts TEXT, actor_id TEXT, actor_role TEXT, family_id TEXT, patient_id TEXT,
  action TEXT, target TEXT, outcome TEXT, detail TEXT);
CREATE TABLE IF NOT EXISTS conversations (
  id TEXT PRIMARY KEY, user_id TEXT, patient_id TEXT, role TEXT, language TEXT, started_at TEXT, updated_at TEXT);
CREATE TABLE IF NOT EXISTS messages (id INTEGER PRIMARY KEY, conv_id TEXT, ts TEXT, who TEXT, text TEXT, tools TEXT);
CREATE INDEX IF NOT EXISTS idx_audit_ts ON audit(ts);
CREATE INDEX IF NOT EXISTS idx_audit_family ON audit(family_id);
CREATE INDEX IF NOT EXISTS idx_messages_conv ON messages(conv_id);
CREATE INDEX IF NOT EXISTS idx_vitals_patient ON vitals(patient_id, kind, ts);
"""

# Tables holding a patient's care record (wiped and regenerated by a demo reset; users/audit/chats are never touched).
CARE_TABLES = ("dose_log", "medications", "checkins", "vitals", "appointments", "alerts", "memories")


def now() -> datetime:
    """Care clock. Set CARECIRCLE_DEMO_TIME=HH:MM to pin the time of day (handy for recording a demo)."""
    t = datetime.now().replace(microsecond=0)
    pinned = os.environ.get("CARECIRCLE_DEMO_TIME")
    if pinned:
        h, m = map(int, pinned.split(":"))
        t = t.replace(hour=h, minute=m, second=0)
    return t


def real_now() -> datetime:
    """The true wall clock. Audit trail, chat history and alert timestamps must never use the pinned demo clock."""
    return datetime.now().replace(microsecond=0)


@contextmanager
def conn():
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    c = sqlite3.connect(DB_PATH)
    c.row_factory = sqlite3.Row
    try:
        yield c
        c.commit()
    finally:
        c.close()


def rows(sql: str, args: tuple = ()) -> list[dict]:
    with conn() as c:
        return [dict(r) for r in c.execute(sql, args).fetchall()]


def one(sql: str, args: tuple = ()) -> dict | None:
    r = rows(sql, args)
    return r[0] if r else None


def _upgrade_old_file() -> None:
    """A database from before multi-family support is moved aside (synthetic data only) rather than migrated."""
    if not DB_PATH.exists():
        return
    c = sqlite3.connect(DB_PATH)
    try:
        version = c.execute("PRAGMA user_version").fetchone()[0]
        has_tables = c.execute("SELECT COUNT(*) FROM sqlite_master WHERE type='table'").fetchone()[0] > 0
    finally:
        c.close()
    if has_tables and version < SCHEMA_VERSION:
        DB_PATH.rename(DB_PATH.with_suffix(f".v{version}.bak"))


def init(seed_if_empty: bool = True) -> None:
    _upgrade_old_file()
    with conn() as c:
        c.executescript(SCHEMA)
        c.execute(f"PRAGMA user_version={SCHEMA_VERSION}")
        empty = c.execute("SELECT COUNT(*) FROM families").fetchone()[0] == 0
    if empty and seed_if_empty:
        from . import seed_data
        seed_data.seed_all()


def reset(scenario: str = "decline", family_id: str | None = None) -> None:
    """Reset demo CARE DATA. With a family id only that family is regenerated; otherwise every family is.
    Users, passwords, the audit log and chat history are never wiped by a reset."""
    from . import seed_data
    if scenario not in seed_data.SCENARIOS:
        raise ValueError(f"scenario must be one of {seed_data.SCENARIOS}")
    with conn() as c:
        c.executescript(SCHEMA)
    seed_data.reseed(scenario, family_id)
